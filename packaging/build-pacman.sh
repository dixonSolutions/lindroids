#!/usr/bin/env bash
# Build the lindroids pacman packages from the .debs packaging/build-debs.sh made: the same files,
# so a pacman install is the same install as an apt one.
#
#   packaging/build-pacman.sh [--debs dist/debs] [--out dist/pacman]
#
# Two flavours, one package name (`lindroids`), unsigned (packaging/repo/build-repo.sh signs):
#   termux  Termux with the pacman bootstrap (service.termux-pacman.dev): from the Termux debs,
#           files under data/data/com.termux/files/usr, arch aarch64/arm/x86_64/i686 as Termux.
#   arch    Arch Linux and derivatives (Arch Linux ARM, Arch Linux 32): from the Debian debs, the
#           static CLI under /usr, arch aarch64/armv7h/x86_64/i686.
# Output: <out>/<flavour>/<arch>/lindroids-<version>-1-<arch>.pkg.tar.xz
#
# Needs bsdtar (libarchive-tools) and xz; reads the .debs with bsdtar, so no dpkg is needed.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$PWD

DEBS=dist/debs
OUT=dist/pacman
while [ $# -gt 0 ]; do
  case "$1" in
    --debs) DEBS=$2; shift 2 ;;
    --out) OUT=$2; shift 2 ;;
    *) echo "build-pacman: unknown argument $1" >&2; exit 2 ;;
  esac
done
for tool in bsdtar xz; do
  command -v $tool >/dev/null || { echo "build-pacman: $tool is required" >&2; exit 1; }
done
: "${SOURCE_DATE_EPOCH:=$(git log -1 --format=%ct 2>/dev/null || date +%s)}"
MAINTAINER="dixonSolutions <lindroids@users.noreply.github.com>"

WORK=$ROOT/target/pacman
rm -rf "$WORK"
mkdir -p "$WORK" "$OUT"

# field <control file> <name>: the first line of a control field.
field() { sed -n "s/^$2: *//p" "$1" | head -1; }

n=0
for deb in "$DEBS"/*.deb; do
  [ -e "$deb" ] || continue
  d=$WORK/pkg
  rm -rf "$d" && mkdir -p "$d"
  bsdtar -xOf "$deb" 'control.tar.*' | bsdtar -xOf - ./control > "$WORK/control"
  bsdtar -xOf "$deb" 'data.tar.*' | bsdtar -xf - -C "$d"
  name=$(field "$WORK/control" Package)
  version=$(field "$WORK/control" Version)
  debarch=$(field "$WORK/control" Architecture)
  case "$debarch" in
    aarch64|arm|x86_64|i686) flavour=termux arch=$debarch ;;
    arm64) flavour=arch arch=aarch64 ;;
    armhf) flavour=arch arch=armv7h ;;
    amd64) flavour=arch arch=x86_64 ;;
    i386) flavour=arch arch=i686 ;;
    *) echo "build-pacman: $deb has unknown architecture $debarch" >&2; exit 1 ;;
  esac
  # pacman's pkgver cannot hold '-'; a Debian revision becomes the pkgrel.
  case "$version" in
    *-*) pkgver=${version%-*} pkgrel=${version##*-} ;;
    *) pkgver=$version pkgrel=1 ;;
  esac
  # As the debs' Recommends/Suggests: the CLI needs nothing, X11 programs and Flatpak apps do.
  if [ $flavour = termux ]; then
    optdepends="xwayland: X11 programs (lindroids run --x11)
libxcb: X11 programs (lindroids run --x11)
xcb-util-cursor: X11 programs (lindroids run --x11)
proot: Flatpak apps
proot-distro: programs from a proot distro (lindroids run --distro)"
  else
    optdepends="xorg-xwayland: X11 programs (lindroids run --x11)
libxcb: X11 programs (lindroids run --x11)
xcb-util-cursor: X11 programs (lindroids run --x11)
flatpak: Flatpak apps"
  fi
  {
    echo "# Generated by packaging/build-pacman.sh from $(basename "$deb")"
    echo "pkgname = $name"
    echo "pkgbase = $name"
    echo "pkgver = $pkgver-$pkgrel"
    echo "pkgdesc = $(field "$WORK/control" Description)"
    echo "url = $(field "$WORK/control" Homepage)"
    echo "builddate = $SOURCE_DATE_EPOCH"
    echo "packager = $MAINTAINER"
    echo "size = $(du -sb "$d" | cut -f1)"
    echo "arch = $arch"
    echo "license = MIT"
    echo "license = Apache-2.0"
    echo "license = MPL-2.0"
    printf '%s\n' "$optdepends" | sed 's/^/optdepend = /'
  } > "$d/.PKGINFO"
  find "$d" -exec touch -h -d "@$SOURCE_DATE_EPOCH" {} +
  # As makepkg: .MTREE (gzipped mtree of everything), then the package with .PKGINFO first.
  (
    cd "$d"
    files=$(find . -mindepth 1 -maxdepth 1 ! -name .PKGINFO -printf '%P\n' | sort)
    # shellcheck disable=SC2086
    LANG=C bsdtar -cf - --format=mtree --uid 0 --gid 0 \
      --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' .PKGINFO $files \
      | gzip -9nc > .MTREE
    touch -d "@$SOURCE_DATE_EPOCH" .MTREE
    dir=$ROOT/$OUT/$flavour/$arch
    [ "${OUT#/}" != "$OUT" ] && dir=$OUT/$flavour/$arch
    mkdir -p "$dir"
    pkg=$dir/$name-$pkgver-$pkgrel-$arch.pkg.tar.xz
    # shellcheck disable=SC2086
    LANG=C bsdtar -cf - --no-xattrs --no-acls --uid 0 --gid 0 --uname root --gname root .PKGINFO .MTREE $files \
      | xz -T0 -c -z - > "$pkg"
    echo "    $flavour/$arch/$(basename "$pkg") ($(du -h "$pkg" | cut -f1))"
  )
  n=$((n + 1))
done
rm -rf "$WORK"
[ $n -gt 0 ] || { echo "build-pacman: no .debs in $DEBS" >&2; exit 1; }
