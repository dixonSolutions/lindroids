#!/usr/bin/env bash
# Build the lindroids Alpine packages (.apk, apk-tools v2 format, which apk-tools 2 and 3 both
# install) from the static musl CLI that scripts/build-release.sh built.
#
#   packaging/build-apk.sh --version 0.1.42 [--dist dist] [--out dist/apk]
#                          [--arches "aarch64 armv7 x86_64 x86"]
#
# For Alpine and postmarketOS (also under proot-distro, UserLAnd, Andronix), Adélie and Chimera.
# Output: <out>/<arch>/lindroids-<version>-r0.apk, unsigned: packaging/repo/build-repo.sh signs
# the repository index (APKINDEX.tar.gz), and apk checks every package against the checksum the
# signed index holds for it.
#
# Only the CLI: these are musl systems, where the glibc xwayland-satellite of the other packages
# cannot run; Alpine has its own xwayland-satellite package, which `lindroids setup x11` installs.
#
# The packages are made the way abuild makes them (abuild-tar --hash for data.tar.gz, datahash in
# .PKGINFO, abuild-tar --cut for control.tar.gz), in an alpine container (podman or docker;
# packaging/container.sh). Input: <dist>/bin/<musl triple>/lindroids.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$PWD
# shellcheck source=packaging/container.sh
. "$ROOT/packaging/container.sh"

ALPINE_IMAGE=${LINDROIDS_ALPINE_IMAGE:-docker.io/library/alpine:3.22}

if [ "${1:-}" = --in-container ]; then
  # In the container: pack every staged package directory <stage>/<arch>/.
  stage=$2
  apk add -q abuild tar coreutils findutils >/dev/null
  for d in "$stage"/*/; do
    d=${d%/}
    out=$(cat "$d.out")
    (
      cd "$d/data"
      find . -mindepth 1 -exec touch -h -d "@$SOURCE_DATE_EPOCH" {} +
      find . -mindepth 1 -printf '%P\0' | LC_ALL=C sort -z \
        | tar --format=posix --pax-option=exthdr.name=%d/PaxHeaders/%f,atime:=0,ctime:=0 \
            --no-recursion --null --mtime="@$SOURCE_DATE_EPOCH" --owner=0 --group=0 --numeric-owner \
            -f - -c -T - \
        | { abuild-tar --hash || true; } | gzip -n -9 > "$d/data.tar.gz"
      # (abuild-tar exits 1 even when it worked; abuild ignores it too. Check the result instead.)
      tar -tzf "$d/data.tar.gz" usr/bin/lindroids >/dev/null
      echo "datahash = $(sha256sum "$d/data.tar.gz" | cut -d' ' -f1)" >> "$d/.PKGINFO"
      cd "$d"
      touch -h -d "@$SOURCE_DATE_EPOCH" .PKGINFO
      printf '.PKGINFO\0' \
        | tar --format=posix --pax-option=exthdr.name=%d/PaxHeaders/%f,atime:=0,ctime:=0 \
            --no-recursion --null --mtime="@$SOURCE_DATE_EPOCH" --owner=0 --group=0 --numeric-owner \
            -f - -c -T - \
        | abuild-tar --cut | gzip -n -9 > control.tar.gz
      mkdir -p "$(dirname "$out")"
      cat control.tar.gz data.tar.gz > "$out"
    )
  done
  exit 0
fi

VERSION=
DIST=dist
OUT=
ARCHES="aarch64 armv7 x86_64 x86"
while [ $# -gt 0 ]; do
  case "$1" in
    --version) VERSION=$2; shift 2 ;;
    --dist) DIST=$2; shift 2 ;;
    --out) OUT=$2; shift 2 ;;
    --arches) ARCHES=$2; shift 2 ;;
    *) echo "build-apk: unknown argument $1" >&2; exit 2 ;;
  esac
done
[ -n "$VERSION" ] || { echo "build-apk: --version is required" >&2; exit 2; }
OUT=${OUT:-$DIST/apk}
mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)
DIST=$(cd "$DIST" && pwd)
: "${SOURCE_DATE_EPOCH:=$(git log -1 --format=%ct 2>/dev/null || date +%s)}"
export SOURCE_DATE_EPOCH
MAINTAINER="dixonSolutions <lindroids@users.noreply.github.com>"
HOMEPAGE="https://github.com/${LINDROIDS_GITHUB_REPO:-dixonSolutions/lindroids}"
COMMIT=$(git rev-parse HEAD 2>/dev/null || true)

WORK=$ROOT/target/apk
rm -rf "$WORK"
mkdir -p "$WORK"

n=0
for arch in $ARCHES; do
  case "$arch" in
    aarch64) triple=aarch64-unknown-linux-musl ;;
    armv7) triple=armv7-unknown-linux-musleabihf ;;
    x86_64) triple=x86_64-unknown-linux-musl ;;
    x86) triple=i686-unknown-linux-musl ;;
    *) echo "build-apk: unknown architecture $arch" >&2; exit 2 ;;
  esac
  bin=$DIST/bin/$triple/lindroids
  [ -f "$bin" ] || { echo "build-apk: missing $bin" >&2; exit 1; }
  d=$WORK/$arch
  mkdir -p "$d/data/usr/bin" "$d/data/usr/share/licenses/lindroids" "$d/data/usr/share/doc/lindroids"
  install -m 755 "$bin" "$d/data/usr/bin/lindroids"
  for f in LICENSE-MIT LICENSE-APACHE; do
    [ -f "$f" ] && install -m 644 "$f" "$d/data/usr/share/licenses/lindroids/$f"
  done
  install -m 644 README.md "$d/data/usr/share/doc/lindroids/README.md"
  [ -f third_party/README.md ] && install -m 644 third_party/README.md "$d/data/usr/share/doc/lindroids/THIRD-PARTY.md"
  find "$d/data" -type d -exec chmod 755 {} +
  {
    echo "# Generated by packaging/build-apk.sh"
    echo "pkgname = lindroids"
    echo "pkgver = $VERSION-r0"
    echo "pkgdesc = Linux GUI programs on Android, in windows and apps of their own"
    echo "url = $HOMEPAGE"
    echo "builddate = $SOURCE_DATE_EPOCH"
    echo "packager = $MAINTAINER"
    # stat, not find -printf: busybox find (Alpine, natively: packaging/container.sh) has no -printf
    echo "size = $(find "$d/data" -type f -exec stat -c %s {} + | awk '{s += $1} END {print s + 0}')"
    echo "arch = $arch"
    echo "origin = lindroids"
    [ -n "$COMMIT" ] && echo "commit = $COMMIT"
    echo "maintainer = $MAINTAINER"
    echo "license = MIT OR Apache-2.0"
  } > "$d/.PKGINFO"
  echo "$OUT/$arch/lindroids-$VERSION-r0.apk" > "$d.out"
  n=$((n + 1))
done
[ $n -gt 0 ] || exit 0

echo "==> apk packages $VERSION (in $ALPINE_IMAGE)"
# shellcheck disable=SC2016
in_container "$ALPINE_IMAGE" "$WORK" "$OUT" "$ROOT/packaging" -- sh -c 'apk add -q bash >/dev/null && bash "$0" --in-container "$1"' \
  "$ROOT/packaging/build-apk.sh" "$WORK"
for arch in $ARCHES; do
  f=$OUT/$arch/lindroids-$VERSION-r0.apk
  [ -s "$f" ] || { echo "build-apk: $f was not made" >&2; exit 1; }
  echo "    $arch/$(basename "$f") ($(du -h "$f" | cut -f1))"
done
rm -rf "$WORK"
